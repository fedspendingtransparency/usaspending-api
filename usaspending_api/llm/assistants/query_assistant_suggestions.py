"""
Curated example prompts shown with a query assistant response.

These are chosen by reason code in code (not generated by the model) so that every suggestion is a query the
filter search assistant is designed to handle.
"""

GENERAL_SUGGESTIONS = [
    "Department of Defense contracts awarded in fiscal year 2025",
    "Grants to universities in Texas in fiscal year 2024",
    "Department of Education spending in fiscal year 2024",
]

SUGGESTIONS_BY_REASON_CODE: dict[str, list[str]] = {
    "no_matching_data": GENERAL_SUGGESTIONS,
    "needs_comparison": GENERAL_SUGGESTIONS,
    "needs_aggregation": [
        "Department of Defense contracts awarded in fiscal year 2025",
        "Contracts over $1 million awarded in fiscal year 2024",
    ],
    "ambiguous_time_period": [
        "Spending in fiscal year 2024",
        "Spending from January 1, 2024 to December 31, 2024",
    ],
    "not_a_search": GENERAL_SUGGESTIONS,
}


def suggestions_for(reason_code: str) -> list[str]:
    return list(SUGGESTIONS_BY_REASON_CODE.get(reason_code, []))
